"""
Career Recommendation — category->ESCO mapping review tool.

Purpose: category_to_esco.json was auto-generated by keyword matching
against ESCO titles, then hand-checked once. A category scoring
HitRate@5 = 0.00 could mean two very different things:
  (a) the mapping is wrong/too narrow (label problem, not a system problem)
  (b) the system genuinely can't retrieve the right occupation (real gap)

This script does NOT re-run retrieval. It just puts everything a human
needs to make that call in one place, for every category — not just the
zero-scoring ones, since "0.50" categories deserve the same scrutiny.

Run from: backend/
    uv run python src/career_recommendation/evaluation/review_category_mappings.py
    uv run python src/career_recommendation/evaluation/review_category_mappings.py --category Arts
    uv run python src/career_recommendation/evaluation/review_category_mappings.py --weak-only

Output: prints to stdout AND writes review_category_mappings.md (readable,
shareable with the team for the "team review" step in the handoff notes).
"""

import argparse
import json
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).parent
GOLD_PATH = HERE / "gold.jsonl"
MAP_PATH = HERE / "category_to_esco.json"
RESULTS_PATH = HERE / "evaluation_results_gold.json"  # optional, for per-category scores
OUT_PATH = HERE / "review_category_mappings.md"

# Categories flagged as weakest in the last evaluate_gold.py run.
# Update this list from your own run's "WEAKEST CATEGORIES" section.
DEFAULT_WEAK_CATEGORIES = [
    "Arts", "BPO", "Management", "Network Security Engineer",
    "Aviation", "Blockchain", "Civil Engineer", "Consultant",
    "Designer", "Education",
]


def load_gold_by_category(path: Path) -> dict[str, list[dict]]:
    by_cat = defaultdict(list)
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rec = json.loads(line)
            by_cat[rec["category"]].append(rec)
    return by_cat


def load_mapping(path: Path) -> dict[str, list[dict]]:
    """
    Real file shape (confirmed against the team's actual category_to_esco.json):
        {
          "_README": "...",
          "categories": {
            "Accountant": [
              {"title": "accountant", "uri": "http://data.europa.eu/esco/occupation/..."},
              ...
            ],
            ...
          }
        }
    Returns {category: [{"title": ..., "uri": ...}, ...]}.
    """
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("categories", data)  # falls back to top-level if shape ever changes


def format_esco_entry(entry) -> str:
    """Entries are {"title": ..., "uri": ...} dicts; tolerate plain strings too."""
    if isinstance(entry, dict):
        title = entry.get("title", "?")
        uri = entry.get("uri", "")
        return f"{title}  ({uri})" if uri else title
    return str(entry)


def load_per_category_scores(path: Path) -> dict[str, float]:
    """Optional: pulls per-category HitRate@5 out of evaluation_results_gold.json
    if it stores that breakdown. Returns {} if not found — script still works."""
    if not path.exists():
        return {}
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        # Adjust this key path to match your actual results JSON structure.
        return data.get("per_category_hit_rate_at_5", {})
    except Exception:
        return {}


def summarize_profile(rec: dict) -> str:
    """One-line summary of a gold resume record for quick human scanning."""
    titles = rec.get("job_titles") or []
    skills = rec.get("skills") or []
    exp = rec.get("experience") or []
    exp_titles = [e.get("title") for e in exp if isinstance(e, dict) and e.get("title")]
    bits = []
    if titles:
        bits.append(f"job_titles={titles[:3]}")
    if exp_titles:
        bits.append(f"experience={exp_titles[:3]}")
    if skills:
        bits.append(f"skills={skills[:6]}")
    return "; ".join(bits) if bits else "(no usable signal fields found)"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--category", help="Review a single category only")
    parser.add_argument(
        "--weak-only", action="store_true",
        help="Only review the categories in DEFAULT_WEAK_CATEGORIES"
    )
    args = parser.parse_args()

    gold_by_cat = load_gold_by_category(GOLD_PATH)
    mapping = load_mapping(MAP_PATH)
    scores = load_per_category_scores(RESULTS_PATH)

    if args.category:
        categories = [args.category]
    elif args.weak_only:
        categories = DEFAULT_WEAK_CATEGORIES
    else:
        categories = sorted(gold_by_cat.keys())

    header = [
        "# Category -> ESCO mapping review\n",
        "For each category: the ESCO occupations it currently maps to (what "
        "counts as a correct answer), and the resumes filed under it (what the "
        "system actually has to match). Read both sides and judge whether the "
        "mapping is reasonable, too narrow, or wrong.\n",
    ]
    all_blocks = []

    for cat in categories:
        recs = gold_by_cat.get(cat, [])
        esco_list = mapping.get(cat, [])
        score = scores.get(cat)

        block = [f"\n## {cat}"]
        if score is not None:
            block.append(f"HitRate@5 (last run): {score:.2f}")
        block.append(f"Resumes in gold set: {len(recs)}")
        if not recs:
            block.append("  ⚠️  NO GOLD RECORDS for this category — check the category name matches gold.jsonl exactly.")
        block.append(f"Mapped ESCO occupations ({len(esco_list)}):")
        if not esco_list:
            block.append("  ⚠️  NONE MAPPED — this category cannot score correct by construction.")
        for uri_or_title in esco_list:
            block.append(f"  - {format_esco_entry(uri_or_title)}")

        block.append("Resume samples in this category:")
        if recs:
            for rec in recs[:5]:  # cap at 5 for readability; category usually has 2
                block.append(f"  - {summarize_profile(rec)}")
        else:
            block.append("  (none)")

        print("\n".join(block))  # live progress, always correct for this category
        all_blocks.append("\n".join(block))

    OUT_PATH.write_text("\n".join(header) + "\n".join(all_blocks), encoding="utf-8")
    print(f"\n\nFull report written to {OUT_PATH}")
    print("\nWhat to do with this:")
    print("  1. For each category with 0 mapped occupations: that's a hard bug — fix the mapping.")
    print("  2. For each category where the resumes clearly don't match the mapped")
    print("     ESCO titles (e.g. a Java resume filed under a mapping with no")
    print("     software-adjacent occupation): the mapping is too narrow, add more.")
    print("  3. For each category where the mapping looks right but score is still")
    print("     low: that's a real retrieval gap, not a label problem — don't touch")
    print("     the mapping, note it as a genuine system limitation instead.")


if __name__ == "__main__":
    main()
